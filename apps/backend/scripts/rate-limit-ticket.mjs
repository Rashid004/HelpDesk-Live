/**
 * Rate-limit test: fire 7 ticket-creation requests back to back as ONE
 * customer. Expect the first 5 -> 201, the 6th and 7th -> 429.
 *
 * Run (from apps/backend), with a customer JWT:
 *   BASE_URL=http://localhost:8000 CUSTOMER_TOKEN=<jwt> \
 *   node scripts/rate-limit-ticket.mjs
 */
import axios from "axios";

const BASE_URL = process.env.BASE_URL ?? "http://localhost:8000";
const TOKEN = process.env.CUSTOMER_TOKEN;
const COUNT = Number(process.env.COUNT ?? 7);

if (!TOKEN) {
  console.error("Missing env: CUSTOMER_TOKEN required");
  process.exit(1);
}

const body = {
  title: "Rate limit test ticket",
  description: "Generated by rate-limit-ticket.mjs to exercise the limiter.",
  category: "other",
  priority: "normal",
};

const createTicket = () =>
  axios
    .post(`${BASE_URL}/api/tickets`, body, {
      headers: { Authorization: `Bearer ${TOKEN}` },
    })
    .then((res) => ({ status: res.status, body: res.data }))
    .catch((err) => ({
      status: err.response?.status,
      body: err.response?.data ?? err.message,
    }));

let blocked = 0;
for (let i = 1; i <= COUNT; i++) {
  // sequential so the counter increments in a predictable order
  const r = await createTicket();
  const msg = r.body?.message ?? r.body?.error ?? "";
  console.log(`#${i}  ->  ${r.status}  ${msg}`);
  if (r.status === 429) blocked++;
}

console.log("\n--- verdict ---");
if (blocked === COUNT - 5) {
  console.log(`PASS: first 5 allowed, remaining ${blocked} got 429`);
  process.exit(0);
}
console.log(`FAIL: ${blocked} blocked, expected ${COUNT - 5}`);
process.exit(1);
